/**
 * Returns a ready-to-use srcset string with mobile 480w and desktop 960w variants
 */
export function getResponsiveSrcSet(mobileUrl: string, desktopUrl: string): string {
  if (!mobileUrl || !desktopUrl) return desktopUrl || mobileUrl || '';
  if (mobileUrl === desktopUrl) return desktopUrl;
  return `${mobileUrl} 480w, ${desktopUrl} 960w`;
}
